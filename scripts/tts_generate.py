import asyncio
import edge_tts
import sys

VOICE = "es-ES-AlvaroNeural"
RATE = "-5%"   # ligeramente más lento para texto solemne

TEXT = """CARTA ENCÍCLICA MAGNIFICA HUMANITAS DEL SANTO PADRE LEÓN XIV
SOBRE LA CUSTODIA DE LA PERSONA HUMANA EN EL TIEMPO DE LA INTELIGENCIA ARTIFICIAL

INTRODUCCIÓN

1. La magnífica humanidad que Dios ha creado se encuentra hoy ante una elección decisiva:
levantar una nueva torre de Babel o edificar la ciudad donde Dios y la humanidad habiten juntos.
Cada generación recibe como herencia la tarea de dar forma a su propio tiempo: hacer madurar la
historia como un lugar donde se proteja la dignidad de cada persona, se promueva la justicia y se
haga posible la fraternidad. Pero en cada época se cierne el riesgo de construir un mundo inhumano
y más injusto. Allí donde la humanidad corre el peligro de perder su rostro, nosotros, los cristianos,
alzamos los ojos hacia el Dios que se hizo carne, sabiendo que el misterio del hombre sólo se
esclarece en el misterio del Verbo encarnado. En Jesucristo, esta magnífica humanidad
encuentra el camino, la verdad y la vida, abriendo a cada uno de nosotros la vía para crecer hacia la
plenitud.

2. Cimentados en Cristo, la piedra viva, experimentamos la acción poderosa y misteriosa del
Espíritu Santo, y creemos que todo esfuerzo humano auténtico por cooperar con Él en pro del bien
será bendecido por el Padre celestial, en quien ponemos nuestra esperanza. Por este motivo,
podemos contribuir con determinación a todas aquellas iniciativas que construyen un mundo más
justo, y podemos invitar a otros a colaborar con nosotros en la promoción del desarrollo integral de
cada ser humano. Deseamos entrar en diálogo con todos los hombres y mujeres de nuestro tiempo,
con quienes participamos juntos en los acontecimientos, las preguntas y las aspiraciones de la
humanidad. Queremos identificar, junto con ellos, nuevos caminos para el bien común y la
promoción de una vida digna para todos.

3. Con este espíritu, en 1891 León XIII publicó la Encíclica Rerum novarum, cuyo 135 aniversario
celebramos este año con profunda gratitud. Con ese documento, mi querido Predecesor impulsó
aquella reflexión sobre la sociedad, la economía y la política que hoy llamamos Doctrina social de
la Iglesia. Han pasado muchas décadas desde entonces, y el Magisterio, los pastores, los teólogos
y los fieles han seguido reflexionando sobre las cuestiones sociales a la luz del Evangelio. Hoy, la
Doctrina social de la Iglesia es un patrimonio de sabiduría, en el que encontramos principios para
pensar, criterios para discernir y juzgar, y orientaciones concretas para actuar.

Las nuevas realidades de nuestro tiempo

4. Si en su momento León XIII hablaba de nuevos asuntos, hoy no podemos limitarnos simplemente
a repetir sus valiosas enseñanzas, sino que debemos pedirle a Dios la sabiduría para interpretar las
grandes tendencias de nuestro tiempo, en particular los avances de la técnica. En los últimos años
se ha hecho cada vez más evidente cuán rápida y profundamente la digitalización, la inteligencia
artificial y la robótica están transformando nuestro mundo.

5. Ahora nos corresponde asumir con lucidez y responsabilidad los retos de nuestro tiempo. Es
necesario adoptar instrumentos normativos adecuados, capaces de salvaguardar la justicia y de
contener los efectos distorsionadores del poder tecnológico.

6. Por esta razón es preciso iniciar un discernimiento compartido capaz de profundizar en las raíces
espirituales y culturales de las transformaciones que se están produciendo.

Dos imágenes bíblicas

7. Para responder a estas preguntas y discernir cómo vivir con responsabilidad en la era de la
inteligencia artificial, me gustaría evocar dos imágenes bíblicas: la construcción de la torre de Babel
y la reconstrucción de los muros de Jerusalén. En el libro del Génesis, el relato de Babel se sitúa
en los orígenes de la humanidad. Los seres humanos deciden construir una ciudad y una torre cuya
cúspide llegue hasta el cielo. El proyecto esconde un profundo engaño: es una obra concebida sin
referencia a Dios, que en lugar de la comunión elige la homogeneización. Babel revela el límite de
toda construcción que surge de la absolutización de lo humano.

8. El libro de Nehemías comienza en un momento de gran vulnerabilidad. Nehemías, antes de
actuar, ayuna, reza e intercede por el pueblo. No impone soluciones desde lo alto. Convoca a las
familias, confía a cada una un tramo de muralla para reconstruir. El relato muestra cómo la ciudad
renace no gracias a la iniciativa de una sola persona, sino a través de la responsabilidad compartida
de todo el pueblo.

9. Los descubrimientos científicos son un talento entregado a la humanidad para que lo haga
fructificar. La tecnología puede curar, conectar, educar, cuidar la Casa común; pero también puede
dividir, descartar, generar nuevas injusticias. La primera elección no es entre un sí o un no a la
tecnología, sino entre construir Babel o reconstruir Jerusalén.

10. Evitemos el síndrome de Babel: la idolatría del lucro que sacrifica a los débiles, la uniformidad
que aplana las diferencias. Elijamos el camino de Nehemías, que pone de relieve el valor del trabajo
compartido.

Edificar en el bien

11. Edificar una ciudad centrada en el bien común exige, ante todo, edificar sobre la roca de la
relación con Dios. Junto con san Agustín, también nosotros podemos decir: Porque nos has hecho
para ti y nuestro corazón está inquieto hasta que descanse en ti.

12. En segundo lugar, edificar en el bien significa aceptar los límites y la fragilidad de la humanidad
sin considerarlos un error que haya que corregir. La Iglesia recuerda, con voz humilde pero firme,
que la verdadera realización no nace de la eliminación de las fragilidades, sino de un crecimiento
armonioso.

13. En tercer lugar, edificar un mundo en el que todos puedan florecer exige una corresponsabilidad
valiente. Ninguna mano, por sí sola, basta para sostener el peso de los desafíos que atraviesa el
mundo. A cada uno corresponde su tramo de muralla.

14. Por último, edificar en el bien requiere un lenguaje evangélico. No bendigamos entusiasmos
ingenuos ni alimentemos miedos estériles. Indiquemos criterios de discernimiento: la dignidad de la
persona, el destino universal de los bienes, la opción por los pobres, el cuidado de la Casa común,
la paz.

Permanecer siendo humanos

15. En la era de la inteligencia artificial, en la que la dignidad humana corre el riesgo de verse
eclipsada por nuevas formas de deshumanización, tenemos el deber urgente de permanecer
profundamente humanos, custodiando con amor esa magnífica humanidad que se nos ha dado y
revelada en plenitud en Cristo, y que ninguna máquina podrá jamás sustituir en su esplendor.

16. A todos los fieles católicos, a todos los cristianos, a todos los hombres y mujeres de buena
voluntad les dirijo un vehemente llamamiento: no temamos ensuciarnos las manos en la obra de
nuestro tiempo. Como Nehemías, oremos, proyectemos con sabiduría, trabajemos con perseverancia,
poniendo a Dios en el horizonte de nuestro actuar y al ser humano en el centro de nuestras
decisiones. Esta es la bendición que imploramos a Dios y la tarea que tenemos por delante: ser
constructores de comunión, no arquitectos de Babel; siervos del Reino que viene, no dueños de
torres destinadas a derrumbarse."""

OUTPUT = sys.argv[1] if len(sys.argv) > 1 else "introduccion.mp3"

async def main():
    print(f"Generando audio: {OUTPUT}")
    print(f"Voz: {VOICE}  |  Rate: {RATE}")
    tts = edge_tts.Communicate(TEXT, voice=VOICE, rate=RATE)
    await tts.save(OUTPUT)
    print(f"OK: {OUTPUT}")

asyncio.run(main())
